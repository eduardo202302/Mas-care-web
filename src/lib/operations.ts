export function normalizeImportKey(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-zA-Z0-9]/g, '')
    .toLowerCase()
}

export function resolveImportField(
  value: string,
): PatientImportField | undefined {
  const normalized = normalizeImportKey(value)
  if ((patientImportFields as readonly string[]).includes(value)) {
    return value as PatientImportField
  }
  return importAliases[normalized]
}

export function autoImportMapping(
  columns: string[],
): Partial<Record<PatientImportField, string>> {
  const mapping: Partial<Record<PatientImportField, string>> = {}
  for (const column of columns) {
    const field = resolveImportField(column)
    if (field && mapping[field] === undefined) mapping[field] = column
  }
  return mapping
}

export function newIdempotencyKey(): string {
  if (typeof globalThis.crypto?.randomUUID === 'function') {
    return globalThis.crypto.randomUUID()
  }
  return `delivery-${Date.now()}-${Math.random().toString(36).slice(2)}`
}

